import {test,expect} from '@playwright/test'
import {expectWarmAnatomyRendered} from './atlas-render'

test('référence féminine détaillée : reins réels, partage et retour aux régions historiques',async({page})=>{
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
 const requests:string[]=[];page.on('request',request=>requests.push(request.url()))
 await page.goto('/#body=female&structure=HRA-region-pelvis')
 await expect(page.locator('main')).toHaveAttribute('data-loaded','true',{timeout:90000})
 expect(requests.some(url=>url.includes('/female-detailed/'))).toBe(false)
 await page.getByLabel('Référence anatomique féminine').selectOption('detail')
 await expect(page.locator('.mode-explanation')).toContainText('591 structures',{timeout:90000})
 await expect(page.locator('main')).toHaveAttribute('data-loaded','true',{timeout:90000})
 await page.getByLabel('Rechercher une structure',{exact:true}).fill('HRA-kidney-left')
 await page.locator('#search-results button').first().click()
 await expect(page.locator('main')).toHaveAttribute('data-selected','HRA-kidney-left')
 await expect(page.getByTestId('structure-detail')).toContainText(/Rein.*gauche/)
 await expect(page.getByTestId('structure-detail')).toContainText('Composants')
 await page.getByRole('button',{name:'Copier le lien de cette structure'}).click()
 await expect(page).toHaveURL(/femaleModel=detail/)
 await page.reload()
 await expect(page.locator('main')).toHaveAttribute('data-loaded','true',{timeout:90000})
 await expect(page.locator('main')).toHaveAttribute('data-selected','HRA-kidney-left')
 await page.screenshot({path:'/tmp/atlas-female-detailed-desktop.png'})
 await page.getByLabel('Référence anatomique féminine').selectOption('regions')
 await expect(page.locator('.mode-explanation')).toContainText('74 structures',{timeout:90000})
 await expect(page).not.toHaveURL(/femaleModel=detail/)
 expect(errors).toEqual([])
})

test('mobile : référence féminine détaillée et fiche repliée restent accessibles',async({page})=>{
 await page.setViewportSize({width:390,height:844})
 await page.goto('/#body=female&femaleModel=detail&mode=detail&structure=HRA-kidney-right')
 await expect(page.locator('main')).toHaveAttribute('data-loaded','true',{timeout:90000})
 await expect(page.getByTestId('structure-detail')).toContainText(/Rein.*droit/)
 await page.getByRole('button',{name:'Réduire la fiche anatomique'}).click()
 await expect(page.getByLabel('Référence anatomique féminine')).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(390)
 await expect.poll(async()=>page.evaluate(()=>{
  const api=(window as any).__CORPUS_TEST__,point=api.project('HRA-kidney-right'),rect=document.querySelector('.stage')!.getBoundingClientRect()
  return Boolean(point&&point.x>rect.left&&point.x<rect.right&&point.y>rect.top&&point.y<rect.bottom)
 })).toBe(true)
 await expectWarmAnatomyRendered(page)
 await page.screenshot({path:'/tmp/atlas-female-detailed-mobile.png'})
 await page.getByRole('button',{name:'Développer la fiche anatomique'}).click()
 await expect(page.getByRole('slider',{name:'Opacité de la structure',exact:true})).toBeVisible()
})

test('cœur féminin : composants réels et capture de sa référence dans une flashcard',async({page})=>{
 await page.route('**/api/flashcards/decks',route=>route.fulfill({json:{decks:[{id:'deck-test',name:'Anatomie'}]}}))
 let saved:any
 await page.route('**/api/flashcards/notes',async route=>{saved=route.request().postDataJSON();await route.fulfill({json:{note:{id:'note-test',...saved}}})})
 await page.goto('/#body=female&femaleModel=detail&mode=detail&structure=FMA7088')
 await expect(page.locator('main')).toHaveAttribute('data-loaded','true',{timeout:90000})
 await expect(page.getByRole('button',{name:'Explorer l’atlas du cœur'})).toHaveCount(0)
 await expect(page.getByText('Composants de l’ensemble 3D (14)',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Créer une flashcard 3D',exact:true}).click()
 await page.getByRole('button',{name:'Créer la flashcard 3D',exact:true}).click()
 await expect.poll(()=>saved?.fields?.scene?.modelKey).toBe('female_extended')
 expect(saved.fields.atlasRevision).toBe('hra-vhf-detail-v1')
 expect(saved.fields.scene.atlasRevision).toBe('hra-vhf-detail-v1')
 expect(saved.fields.targets[0].structureId).toBe('FMA7088')
})
