import { chromium } from '@playwright/test'
const browser=await chromium.launch({executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']})
const page=await browser.newPage({viewport:{width:1440,height:900}})
page.on('pageerror',e=>console.log('ERROR',e.message))
page.on('console',m=>{if(m.type()==='error')console.log('CONSOLE',m.text())})
await page.goto('http://127.0.0.1:5173')
await page.locator('main[data-loaded="true"]').waitFor({timeout:90000})
await page.waitForTimeout(400)
console.log('INITIAL',await page.evaluate(()=>window.__CORPUS_TEST__.state()))
await page.screenshot({path:'tests/artifacts/white-desktop.png'})
await page.getByRole('switch',{name:'Muscles',exact:true}).click()
await page.locator('main[data-loaded="true"]').waitFor({timeout:90000})
await page.waitForTimeout(400)
console.log('MUSCLES',await page.evaluate(()=>window.__CORPUS_TEST__.state()))
await page.screenshot({path:'tests/artifacts/white-muscles.png'})
await page.getByRole('combobox').fill('deltoïde')
console.log('OPTIONS',await page.getByRole('option').allTextContents())
await page.getByRole('option').first().click()
await page.getByRole('button',{name:'Isoler',exact:true}).click()
await page.waitForTimeout(1500)
await page.screenshot({path:'tests/artifacts/white-isolated.png'})
await page.getByRole('button',{name:'Fermer la fiche'}).click()
await page.setViewportSize({width:393,height:852})
await page.waitForTimeout(1300)
await page.screenshot({path:'tests/artifacts/white-mobile.png'})
console.log('OVERFLOW',await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))
await browser.close()
