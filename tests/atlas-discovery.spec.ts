import {test,expect} from '@playwright/test'
test('colonne : accès visible depuis l’accueil et vertèbres détaillées sélectionnables',async({page})=>{
 await page.goto('/')
 await page.getByRole('button',{name:'Explorer Colonne en 3D',exact:true}).click()
 await expect(page).toHaveURL(/mode=detail/)
 await expect(page.locator('main')).toHaveAttribute('data-selected','FMA13478',{timeout:90000})
 const nav=page.getByRole('region',{name:'Navigation anatomique'})
 await expect(nav.getByText('Composants de l’ensemble 3D (47)',{exact:true})).toBeVisible()
 await nav.getByRole('button',{name:/^C1 ·/}).click()
 await expect(page.locator('.original-name')).toHaveText('atlas')
 await expect(page.getByRole('slider',{name:'Opacité de la structure',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Réviser ces structures en 3D'}).click()
 await expect(page.getByLabel('Type d’exercice anatomique')).toBeVisible()
})
test('vue d’ensemble : ouvrir un composant du cœur bascule réellement vers le modèle détaillé',async({page})=>{
 await page.goto('/#mode=overview&structure=FMA7088')
 const nav=page.getByRole('region',{name:'Navigation anatomique'})
 await nav.getByRole('button',{name:'Paroi de l’atrium droit 3D',exact:true}).click()
 await expect(page).toHaveURL(/mode=detail/)
 await expect(page.locator('main')).toHaveAttribute('data-selected','FMA9457',{timeout:90000})
 await expect(page.locator('main')).toHaveAttribute('data-loaded','true',{timeout:90000})
})
test('mobile : le raccourci colonne reste visible avec les trois autres régions',async({page})=>{
 await page.setViewportSize({width:390,height:844})
 await page.goto('/')
 await expect(page.locator('.region-blocks button')).toHaveCount(4)
 await page.getByRole('button',{name:'Explorer Colonne en 3D',exact:true}).click()
 await expect(page.locator('main')).toHaveAttribute('data-selected','FMA13478',{timeout:90000})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(390)
})
